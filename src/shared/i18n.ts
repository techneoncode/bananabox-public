/** Builds a translator; unknown `flag.*` keys are prettified, other unknown keys fall back to English then to the key. */
export function createT(lang: Lang): (key: string, params?: Record<string, string | number>) => string {
  return (key, params) => {
    let text = (hostIde === 'CLion' ? clion[lang][key] : undefined) ?? dictionaries[lang][key] ?? dictionaries.en[key];
    if (text === undefined) {
      text = key.startsWith('flag.') ? key.slice(5).replace(/[-_]/g, ' ') : key;
    }
    text = text.replaceAll('VS Code', hostIde);
    return params ? text.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`)) : text;
  };
}
